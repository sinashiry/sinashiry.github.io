// Keys accepted by the strict Pages CMS configuration schema (lib/config-schema.ts).
const KEYS={
  root:['cache','hide','media','content','components','actions','settings'],
  settings:['config','cache','hide','content','commit'],commit:['templates','identity'],templates:['create','update','delete','rename'],
  media:['input','output','path','extensions','categories','rename','commit','name','label','actions'],
  action:['name','label','workflow','ref','cancelable','scope','confirm','fields'],confirm:['title','message','button'],
  leaf:['name','label','description','type','path','operations','filename','exclude','view','format','delimiters','subfolders','fields','list','commit','actions'],
  group:['name','label','description','type','items'],operations:['create','rename','delete'],filename:['template','field'],
  view:['layout','node','fields','primary','sort','search','default'],viewDefault:['search','sort','order'],
  field:['name','label','description','component','default','fields','type','list','hidden','readonly','required','pattern','options','blocks','blockKey'],
  list:['min','max','collapsible'],pattern:['regex','message'],
};
const TYPES=['boolean','code','date','file','image','number','reference','rich-text','select','string','text','uuid','object','block'];
const NAME=/^[a-zA-Z0-9-_]+$/;
const only=(obj,keys,where)=>{for(const k of Object.keys(obj))assert.ok(keys.includes(k),`${where}: unexpected key "${k}"`);};

function checkField(f,where,media){
  only(f,KEYS.field,where);assert.match(f.name,NAME,where);assert.ok(TYPES.includes(f.type),`${where}: type ${f.type}`);
  if(isObject(f.list)){only(f.list,KEYS.list,where);assert.ok('collapsible' in f.list,`${where}: the schema requires list.collapsible`);if(f.list.max!==undefined)assert.ok(f.list.max>=1&&f.list.min<=f.list.max,where);}
  if(isObject(f.pattern)){only(f.pattern,KEYS.pattern,where);new RegExp(f.pattern.regex);}
  if(f.type==='object'){assert.ok(Array.isArray(f.fields)&&f.fields.length,`${where}: object needs fields`);f.fields.forEach(x=>checkField(x,`${where}.${x.name}`,media));}
  if(f.type==='select')assert.ok(f.options?.values?.length,`${where}: select needs values`);
  if(['file','image'].includes(f.type))assert.ok(media.includes(f.options?.media),`${where}: unknown media ${f.options?.media}`);
}

test('configuration uses only keys of the Pages CMS schema', () => {
  only(config,KEYS.root,'root');only(config.settings,KEYS.settings,'settings');only(config.settings.commit,KEYS.commit,'commit');only(config.settings.commit.templates,KEYS.templates,'templates');
  const media=config.media.map(m=>{only(m,KEYS.media,'media');assert.match(m.input,/^[^/].*[^/]$/);assert.match(m.output,/^\/?[^/].*[^/]$/);return m.name;});
  for(const a of config.actions){only(a,KEYS.action,'action');only(a.confirm,KEYS.confirm,'confirm');assert.match(a.name,NAME);}
  const names=new Set();
  for(const e of config.content){
    if(e.type==='group'){only(e,KEYS.group,e.name);e.items.forEach(x=>assert.notEqual(x.type,'group'));}
    for(const leaf of e.type==='group'?e.items:[e]){
      only(leaf,KEYS.leaf,leaf.name);assert.match(leaf.name,NAME);assert.ok(!names.has(leaf.name),`duplicate ${leaf.name}`);names.add(leaf.name);
      assert.ok(['file','collection'].includes(leaf.type));assert.match(leaf.path,/^[^/].*[^/]$/);
      only(leaf.operations||{},KEYS.operations,leaf.name);
      if(isObject(leaf.filename))only(leaf.filename,KEYS.filename,leaf.name);
      if(leaf.view){only(leaf.view,KEYS.view,leaf.name);only(leaf.view.default||{},KEYS.viewDefault,leaf.name);assert.ok(Array.isArray(leaf.view.sort));}
      leaf.fields.forEach(f=>checkField(f,`${leaf.name}.${f.name}`,media));
    }
  }
});

