test('form patterns agree with the build checks on current and sample values', () => {
  const https=new RegExp(HTTPS_PATTERN),email=new RegExp(EMAIL_PATTERN);
  for(const v of ['https://github.com/sinashiry','https://www.linkedin.com/in/sina-shiri-50b371162/','https://example.org:8443/a?b=c#d'])assert.ok(https.test(v)&&validHttps(v),v);
  for(const v of ['http://example.org','https://user@example.org/','https://a b.org','https://'])assert.ok(!https.test(v)&&!validHttps(v),v);
  for(const v of ['info@sina-shiri.com','a.b@example.org'])assert.ok(email.test(v)&&validEmail(v),v);
  for(const v of ['info@sina-shiri','a?b@example.org','a b@example.org'])assert.ok(!email.test(v)&&!validEmail(v),v);
});

test('blog and paper form rules agree with the build on current and sample values', () => {
  const entries=flat(config.content),posts=entries.find(e=>e.name==='posts'),papers=entries.find(e=>e.name==='papers');
  const field=(c,name)=>c.fields.find(f=>f.name===name),accepts=(f,v)=>new RegExp(f.pattern.regex).test(v)&&v.length<=(f.options?.maxlength??Infinity);
  const slug=field(posts,'slug');
  for(const v of ['bench-notes','a1','raspberry-pi-camera-notes','x'.repeat(80),'admin-notes','blog2'])assert.ok(accepts(slug,v)&&validSlug(v),v);
  for(const v of ['','x'.repeat(81),'Bench-Notes','bad--slug','-lead','trail-','a/b','notes.md','my post',...RESERVED_SLUGS])assert.ok(!accepts(slug,v)&&!validSlug(v),v);
  const year=field(papers,'year');
  for(const v of ['1900','1999','2026','2100'])assert.ok(accepts(year,v)&&validYear(v),v);
  for(const v of ['1899','2101','2150','0000','26','20255'])assert.ok(!accepts(year,v)&&!validYear(v),v);
  const doi=field(papers,'doi');
  assert.ok(accepts(doi,'10.1234/'+'x'.repeat(192))&&validDoi('10.1234/'+'x'.repeat(192)));
  assert.ok(!accepts(doi,'10.1234/'+'x'.repeat(193)),'the CMS limit is the build limit of 200 characters');
  for(const name of ['link','code']){
    const f=field(papers,name);
    for(const v of ['','https://tches.iacr.org/index.php/TCHES/article/view/12345','https://example.org/a?b=1&c=2'])assert.ok(accepts(f,v)&&(!v||validCollectionHttps(v)),v);
    for(const v of ['https://example.org/papers/café','https://exämple.org/','http://example.org','https://user@example.org/'])assert.ok(!accepts(f,v)&&!validCollectionHttps(v),v);
  }
  assert.equal(field(posts,'body').options.maxlength,BODY_LIMIT,'the CMS and the build both count characters');
});
