test('--check fails when .pages.yml is stale and a write repairs it', () => {
  const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'pages-config-'));
  try{
    for(const f of ['content/structure.json','content/contract.json','content/labels.json']){fs.mkdirSync(path.dirname(path.join(tmp,f)),{recursive:true});fs.copyFileSync(f,path.join(tmp,f));}
    assert.equal(quiet(()=>run(['--check'],tmp)),1,'missing file is stale');
    fs.writeFileSync(path.join(tmp,CONFIG_FILE),text.replace('maxlength: 500','maxlength: 501'));
    assert.equal(quiet(()=>run(['--check'],tmp)),1);
    assert.equal(quiet(()=>run([],tmp)),0);
    assert.equal(fs.readFileSync(path.join(tmp,CONFIG_FILE),'utf8'),text);
    assert.equal(quiet(()=>run(['--check'],tmp)),0);
    const labels=JSON.parse(fs.readFileSync(path.join(tmp,'content/labels.json'),'utf8'));labels.fields['profile.name']='Full name';
    fs.writeFileSync(path.join(tmp,'content/labels.json'),JSON.stringify(labels));
    assert.equal(quiet(()=>run(['--check'],tmp)),1,'a label change makes the config stale');
  }finally{fs.rmSync(tmp,{recursive:true,force:true});}
});

